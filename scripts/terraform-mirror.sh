#!/usr/bin/env bash
# Builds an offline Terraform provider mirror under ./.tools/tf-mirror (gitignored)
# and writes ./.tools/terraformrc so `terraform init` never contacts
# registry.terraform.io (which is unreachable from the development sandbox).
#
# Integrity chain (all three must pass, otherwise the script exits non-zero and
# removes the partial download):
#   1. SHA256SUMS is signed by the HashiCorp Security key. The key is fetched from
#      hashicorp.com and its primary fingerprint must equal HASHICORP_KEY_FPR
#      (published at https://www.hashicorp.com/security). Verified with gpgv when
#      gpg is installed; set TF_MIRROR_REQUIRE_SIGNATURE=1 (CI does) to make a
#      missing gpg a hard failure.
#   2. The provider zip's SHA256 must match the line in that SHA256SUMS file.
#   3. The same SHA256 must match the value pinned in this script (reviewed pin).
#
# Versions are pinned here and recorded in infra/terraform/README.md. Update both
# together. Only hashicorp/aws is mirrored; no other provider is used.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS="${ROOT}/.tools"
MIRROR="${TOOLS}/tf-mirror"
CACHE="${TOOLS}/tf-mirror-cache"

AWS_PROVIDER_VERSION="6.67.0"
# linux_amd64 zip SHA256, copied from the signed terraform-provider-aws_6.67.0_SHA256SUMS.
AWS_PROVIDER_LINUX_AMD64_SHA256="4ce94853264097dd7f4542b3cfd18d2b98b06d23321db45d5e384ea275a57f63"
HASHICORP_KEY_FPR="C874011F0AB405110D02105534365D9472D7468F"
HASHICORP_KEY_URL="https://www.hashicorp.com/.well-known/pgp-key.txt"
RELEASES="https://releases.hashicorp.com/terraform-provider-aws/${AWS_PROVIDER_VERSION}"
TARGET="linux_amd64"

PKG_DIR="${MIRROR}/registry.terraform.io/hashicorp/aws/${AWS_PROVIDER_VERSION}/${TARGET}"
ZIP_NAME="terraform-provider-aws_${AWS_PROVIDER_VERSION}_${TARGET}.zip"
SUMS_NAME="terraform-provider-aws_${AWS_PROVIDER_VERSION}_SHA256SUMS"

mkdir -p "${CACHE}" "${MIRROR}"

fail() {
  echo "terraform-mirror: $*" >&2
  exit 1
}

write_rc() {
  cat >"${TOOLS}/terraformrc" <<EOF
# Generated by scripts/terraform-mirror.sh. Offline provider installation:
# hashicorp/aws comes only from the checksum-verified filesystem mirror.
disable_checkpoint = true

provider_installation {
  filesystem_mirror {
    path    = "${MIRROR}"
    include = ["registry.terraform.io/hashicorp/aws"]
  }
  direct {
    exclude = ["registry.terraform.io/hashicorp/aws"]
  }
}
EOF
}

# Marker lives outside the package directory: Terraform hashes every file inside it.
MARKER="${CACHE}/aws_${AWS_PROVIDER_VERSION}_${TARGET}.verified-sha256"

if [[ -x "${PKG_DIR}/terraform-provider-aws_v${AWS_PROVIDER_VERSION}_x5" && -f "${MARKER}" ]] &&
  [[ "$(cat "${MARKER}")" == "${AWS_PROVIDER_LINUX_AMD64_SHA256}" ]]; then
  write_rc
  echo "terraform-mirror: hashicorp/aws ${AWS_PROVIDER_VERSION} already mirrored (sha256 ${AWS_PROVIDER_LINUX_AMD64_SHA256})"
  echo "terraform-mirror: TF_CLI_CONFIG_FILE=${TOOLS}/terraformrc"
  exit 0
fi

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

curl -fsSL -o "${work}/${SUMS_NAME}" "${RELEASES}/${SUMS_NAME}"
curl -fsSL -o "${work}/${SUMS_NAME}.sig" "${RELEASES}/${SUMS_NAME}.sig"
curl -fsSL -o "${work}/${ZIP_NAME}" "${RELEASES}/${ZIP_NAME}"

# 1. Signature over SHA256SUMS.
if command -v gpg >/dev/null 2>&1 && command -v gpgv >/dev/null 2>&1; then
  curl -fsSL -o "${work}/hashicorp.asc" "${HASHICORP_KEY_URL}"
  fpr="$(gpg --batch --with-colons --show-keys "${work}/hashicorp.asc" 2>/dev/null | awk -F: '$1=="fpr"{print $10; exit}')"
  [[ "${fpr}" == "${HASHICORP_KEY_FPR}" ]] || fail "HashiCorp key fingerprint mismatch: got '${fpr}'"
  gpg --batch --dearmor <"${work}/hashicorp.asc" >"${work}/hashicorp.gpg"
  status="$(gpgv --status-fd 1 --keyring "${work}/hashicorp.gpg" "${work}/${SUMS_NAME}.sig" "${work}/${SUMS_NAME}" 2>/dev/null || true)"
  grep -Eq "^\[GNUPG:\] VALIDSIG [0-9A-F]+ .* ${HASHICORP_KEY_FPR}\$" <<<"${status}" ||
    fail "SHA256SUMS signature did not verify against ${HASHICORP_KEY_FPR}"
  echo "terraform-mirror: SHA256SUMS signature verified (primary key ${HASHICORP_KEY_FPR})"
elif [[ "${TF_MIRROR_REQUIRE_SIGNATURE:-0}" == "1" ]]; then
  fail "gpg/gpgv not installed and TF_MIRROR_REQUIRE_SIGNATURE=1"
else
  echo "terraform-mirror: WARNING gpg not installed; signature NOT verified (pinned SHA256 still enforced)" >&2
fi

# 2. Zip hash matches the (signed) SHA256SUMS line.
published="$(awk -v n="${ZIP_NAME}" '$2==n{print $1}' "${work}/${SUMS_NAME}")"
[[ -n "${published}" ]] || fail "${ZIP_NAME} not listed in ${SUMS_NAME}"
actual="$(sha256sum "${work}/${ZIP_NAME}" | awk '{print $1}')"
[[ "${actual}" == "${published}" ]] || fail "zip sha256 ${actual} != published ${published}"

# 3. Zip hash matches the reviewed pin in this script.
[[ "${actual}" == "${AWS_PROVIDER_LINUX_AMD64_SHA256}" ]] ||
  fail "zip sha256 ${actual} != pinned ${AWS_PROVIDER_LINUX_AMD64_SHA256}"

rm -rf "${PKG_DIR}"
mkdir -p "${PKG_DIR}"
unzip -q -o "${work}/${ZIP_NAME}" -d "${PKG_DIR}"
cp "${work}/${ZIP_NAME}" "${work}/${SUMS_NAME}" "${work}/${SUMS_NAME}.sig" "${CACHE}/"
printf '%s' "${actual}" >"${MARKER}"

write_rc
echo "terraform-mirror: mirrored hashicorp/aws ${AWS_PROVIDER_VERSION} ${TARGET} (sha256 ${actual})"
echo "terraform-mirror: TF_CLI_CONFIG_FILE=${TOOLS}/terraformrc"
