/**
 * Machine-readable integration inventory (spec section 16: "For every
 * integration record method, endpoint, version, auth mechanism, schema, rate
 * limit, retention, data class and source"). docs/DECISIONS.md D-07 makes this
 * file the authoritative inventory; human summaries derive from it.
 *
 * Rules:
 *  - a value that has not been verified for OUR tenant/plan is "UNKNOWN" — it is
 *    never inferred from a product page, a demo tenant or a guess;
 *  - an endpoint is recorded only when a public document in the source register
 *    (or a named public standard) documents it; otherwise "UNKNOWN";
 *  - status describes the LIVE integration:
 *      IMPLEMENTED_OFFLINE  code path implemented against the documented API and
 *                           tested offline (emulated contract tests); NOT sandbox
 *                           evidence and NOT production readiness;
 *      BLOCKED              a known prerequisite (PRQ-xxx) is missing;
 *      UNKNOWN              nothing can be determined from this repository;
 *  - retention durations are set by privacy counsel (PRQ-025); none is invented.
 *
 * Public documents are evidence of a POSSIBLE capability only; tenant tests are
 * evidence of actual availability (spec section 16).
 */
