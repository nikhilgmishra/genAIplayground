/** Validates the inventory (strict schema, unique ids) and returns it. */
export function validatedInventory(entries: readonly IntegrationInventoryEntry[] = INTEGRATION_INVENTORY): IntegrationInventoryEntry[] {
  const out = entries.map((e) => IntegrationInventoryEntrySchema.parse(e));
  const ids = new Set<string>();
  for (const e of out) {
    if (ids.has(e.id)) throw new ValidationError("INVENTORY_DUPLICATE_ID");
    ids.add(e.id);
  }
  return out;
}

export function inventoryFor(integrationId: string): IntegrationInventoryEntry[] {
  return INTEGRATION_INVENTORY.filter((e) => e.integrationId === integrationId);
}
