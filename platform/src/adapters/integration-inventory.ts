export const InventoryStatus = z.enum(["UNKNOWN", "BLOCKED", "IMPLEMENTED_OFFLINE"]);
export type InventoryStatus = z.infer<typeof InventoryStatus>;

const Text = z.string().min(1).max(600);

export const IntegrationInventoryEntrySchema = z.strictObject({
  id: z.string().regex(/^[a-z][a-z0-9_.-]{2,80}$/),
  system: Text,
  /** Adapter integration id / config adapter key, or the owning component for inbound transports. */
  integrationId: z.string().regex(/^[a-z][a-z0-9-]{2,63}$/),
  direction: z.enum(["outbound", "inbound"]),
  operation: Text,
  method: Text,
  endpoint: Text,
  version: Text,
  authMechanism: Text,
  schemaRef: Text,
  rateLimit: Text,
  retention: Text,
  dataClass: z.union([z.literal("UNKNOWN"), z.literal("NONE"), z.array(DataClass).min(1).max(4)]),
  classification: z.union([z.literal("UNKNOWN"), z.array(Classification).min(1).max(6)]),
  /** Source-register id (S1..S24), a named public standard, or NONE_SUPPLIED. */
  sourceRef: z.string().regex(/^(S\d{1,2}|STANDARD|NONE_SUPPLIED|NOT_IN_SOURCE_REGISTER)$/),
  sourceDoc: Text,
  status: InventoryStatus,
  implementation: z.strictObject({
    live: z.string().max(200).nullable(),
    fixture: z.string().max(200).nullable(),
    tests: z.array(z.string().max(200)).max(8),
  }),
  prerequisites: z.array(z.string().regex(/^PRQ-\d{3}$/)).max(12),
  vendorQuestions: z.array(z.string().regex(/^VQ-[A-Z]{2,4}-\d{2}$/)).max(12),
  trustBoundaries: z.array(z.string().regex(/^TB-\d{2}$/)).max(6),
  notes: z.string().max(1200),
});
export type IntegrationInventoryEntry = z.infer<typeof IntegrationInventoryEntrySchema>;

