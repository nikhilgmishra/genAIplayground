/**
 * Renders docs/resolution-contracts.md from the contract objects (single source of
 * truth). Pure; the CLI writes or checks the file.
 */
import type { ResolutionContract } from "../../protocol/index.js";
import { DRAFT_NOTICE } from "./define.js";

export interface ContractToolRef {
  name: string;
  version: string;
  permissions: readonly string[];
  contracts: readonly string[];
}

const esc = (s: string): string => s.replace(/\|/g, "\\|");
const list = (items: readonly string[]): string => (items.length === 0 ? "none" : items.map((i) => `\`${esc(i)}\``).join(", "));
const bullets = (items: readonly string[]): string => (items.length === 0 ? "- none" : items.map((i) => `- ${i}`).join("\n"));

export function renderContractsMarkdown(contracts: readonly ResolutionContract[], tools: readonly ContractToolRef[]): string {
  const lines: string[] = [];
  lines.push("# Resolution contracts");
  lines.push("");
  lines.push("<!-- GENERATED by platform/src/business/contracts/cli-generate-doc.ts from platform/src/business/contracts/*.ts. Do not edit by hand; run `cd platform && npx tsx src/business/contracts/cli-generate-doc.ts` (CI: `--check`). -->");
  lines.push("");
  lines.push(
    "Status: **DRAFT**. Every contract below is an engineering default pending business, clinical and privacy approval. None is approved; the coding agent cannot approve a contract (`approvedBy` is always empty). Spec section 4: each workflow has a versioned contract; unsupported workflows end in honest intake or a human route.",
  );
  lines.push("");
  lines.push("Outcome rules (ACT-04): `RESOLVED` requires the contract's exact success evidence (for a change, a COMMITTED commit receipt of the contract's action kind for this call). Workflow acceptance, case or support-request creation is `REQUEST_ACCEPTED`; a read-only answer is `INFORMATION_PROVIDED`; a transfer is `TRANSFERRED` only after `CALLER_CONFIRMED_CONNECTED`. A hang-up, an HTTP 200 or a created Case never sets `RESOLVED`.");
  lines.push("");
  lines.push("| Contract | Intent | Audiences | Assurance | Source | Resolved outcome | Confirmation | Escalation owner | Deadline | After hours | Tools |");
  lines.push("|---|---|---|---|---|---|---|---|---|---|---|");
  for (const c of contracts) {
    const served = tools.filter((t) => t.contracts.includes(c.contractId)).map((t) => t.name);
    lines.push(
      `| [\`${c.contractId}\`](#${c.contractId.replace(/@/g, "")}) | ${c.intent} | ${c.eligibleAudiences.join(", ")} | ${c.requiredAssurance} | ${c.sourceSystem} | ${c.resolvedOutcome} | ${c.callerConfirmationRequired ? "required" : "no"} | \`${c.escalationOwner}\` | ${c.serviceDeadline ?? "none"} | ${c.afterHoursBehavior} | ${served.length ? served.map((n) => `\`${n}\``).join(", ") : "none"} |`,
    );
  }
  for (const c of contracts) {
    const served = tools.filter((t) => t.contracts.includes(c.contractId));
    lines.push("");
    lines.push(`## ${c.contractId}`);
    lines.push("");
    lines.push(`**${esc(c.title)}** - status \`${c.status}\`. ${DRAFT_NOTICE}`);
    lines.push("");
    lines.push(`- Intent: \`${c.intent}\``);
    lines.push(`- Eligible audiences: ${list(c.eligibleAudiences)}`);
    lines.push(`- Required assurance: \`${c.requiredAssurance}\` (application policy tier, not a NIST AAL)`);
    lines.push(`- Source system: \`${c.sourceSystem}\``);
    lines.push(`- Permitted fields: ${list(c.permittedFields)}`);
    lines.push(`- Allowed actions: ${list(c.allowedActions)}`);
    lines.push(`- Caller confirmation: ${c.callerConfirmationRequired ? "required (trusted confirmation bound to the prepared-action digest, ACT-01)" : "not required"}`);
    lines.push(`- Escalation owner: \`${c.escalationOwner}\``);
    lines.push(`- Service deadline: ${c.serviceDeadline ? `\`${c.serviceDeadline}\` (engineering default pending support operations)` : "none"}`);
    lines.push(`- After-hours behaviour: \`${c.afterHoursBehavior}\``);
    lines.push(`- Outcome when the success evidence exists: \`${c.resolvedOutcome}\``);
    lines.push(`- Served by tools: ${served.length ? served.map((t) => `\`${t.name}@${t.version}\` (${t.permissions.map((p) => `\`${p}\``).join(", ")})`).join(", ") : "none"}`);
    lines.push("");
    lines.push("Exact success evidence:");
    lines.push("");
    lines.push(bullets(c.successEvidence));
    lines.push("");
    lines.push("Prohibited assertions:");
    lines.push("");
    lines.push(bullets(c.prohibitedAssertions));
    lines.push("");
    lines.push("Human boundary:");
    lines.push("");
    lines.push(bullets(c.humanBoundary));
  }
  lines.push("");
  return lines.join("\n");
}
