#!/usr/bin/env node
// Compares an observed Talkdesk tenant configuration against talkdesk/expected-config.yaml.
//
// Offline only. The observed file is produced by the operator from a documented export
// (method UNKNOWN until Talkdesk documents one, VQ-TD-37) or by transcription into
// talkdesk/observed-config.template.yaml. See talkdesk/drift-check.md.
//
// Usage:
//   node talkdesk/tools/drift-check.mjs <observed.yaml> [--expected <file>] [--openapi <file>] [--json]
//   node talkdesk/tools/drift-check.mjs --emit-template [--expected <file>]
//
// Exit codes: 0 CLEAN (every expected leaf MATCHes), 1 DRIFT, 2 INCOMPLETE (anything
// unobserved, not recorded or a new fact awaiting review — never a pass), 3 usage/parse error.
import path from "node:path";
import { pathToFileURL } from "node:url";
import { compareConfig, compareOpenApi, loadYaml, parseYaml, readText, stringifyYaml, TALKDESK_DIR, toObservationTemplate } from "./lib.mjs";

const TEMPLATE_HEADER = `# Observed Talkdesk tenant configuration — operator transcription template.
#
# GENERATED by: node talkdesk/tools/drift-check.mjs --emit-template > talkdesk/observed-config.template.yaml
# Do not edit the structure. Copy this file OUTSIDE the repository (synthetic sandbox facts only,
# no secrets, no PHI), replace each UNOBSERVED with the value the tenant shows (export or UI),
# then run: node talkdesk/tools/drift-check.mjs <your-copy.yaml>
#
# - Leave UNOBSERVED where the value cannot be seen; write UNKNOWN if the tenant does not expose it.
# - aiAgent.guardrail.observedText and templates[].observedText: paste the exact text configured
#   in the tenant (no trailing newline); drift-check derives sha256 and character count.
# - Lists such as fallbackDestinationIds and steps are order-sensitive; tools, languages,
#   phrases, agents and writtenBy lists are compared as sets.
# - Record for each section, outside this file, the UI path or export reference used as evidence.
`;

export function emitTemplate(expectedFile) {
  const expected = loadYaml(expectedFile);
  const tree = toObservationTemplate(expected.tenantConfiguration, "");
  return TEMPLATE_HEADER + stringifyYaml({ schemaVersion: "vsp.talkdesk.observed-config.v1", observedAt: "UNOBSERVED", observedBy: "UNOBSERVED", evidenceRefs: "UNOBSERVED", tenantConfiguration: tree });
}

export function runDriftCheck({ observedFile, expectedFile, openapiFile }) {
  const expected = loadYaml(expectedFile);
  const observed = loadYaml(observedFile);
  if (!observed || typeof observed !== "object" || !("tenantConfiguration" in observed)) {
    throw new Error("observed file has no tenantConfiguration");
  }
  const result = compareConfig(expected.tenantConfiguration, observed.tenantConfiguration);
  if (openapiFile) {
    const text = readText(openapiFile);
    const doc = openapiFile.endsWith(".json") ? JSON.parse(text) : parseYaml(text);
    result.openapi = compareOpenApi(expected.tenantConfiguration?.studio?.httpSteps, doc);
    if (result.openapi.some((r) => r.status !== "OPENAPI_MATCH") && result.verdict === "CLEAN") result.verdict = "DRIFT";
  }
  return result;
}

function printHuman(result) {
  const order = ["DRIFT", "UNEXPECTED", "NEW_FACT", "NOT_RECORDED", "UNOBSERVED", "MATCH"];
  console.log(`drift-check verdict: ${result.verdict}`);
  console.log(`counts: ${order.map((s) => `${s}=${result.counts[s] ?? 0}`).join(" ")}`);
  for (const status of ["DRIFT", "UNEXPECTED", "NEW_FACT", "NOT_RECORDED"]) {
    const rows = result.rows.filter((r) => r.status === status);
    if (rows.length === 0) continue;
    console.log(`\n${status}:`);
    for (const r of rows) {
      console.log(`  ${r.path}\n    expected: ${JSON.stringify(r.expected)}\n    observed: ${JSON.stringify(r.observed)}`);
    }
  }
  if (result.openapi) {
    console.log("\nOpenAPI comparison (telephony-control operations):");
    for (const r of result.openapi) console.log(`  ${r.status} ${r.method} ${r.path} (${r.operationId})`);
  }
  if (result.verdict !== "CLEAN") {
    console.log("\nNot CLEAN: unobserved, unrecorded or new-fact values are not a pass (OPS-03).");
  }
}

function main(argv) {
  const args = argv.slice(2);
  const opt = (name) => {
    const i = args.indexOf(name);
    if (i === -1) return null;
    const v = args[i + 1];
    args.splice(i, 2);
    return v ?? null;
  };
  const flag = (name) => {
    const i = args.indexOf(name);
    if (i === -1) return false;
    args.splice(i, 1);
    return true;
  };
  const expectedFile = opt("--expected") ?? path.join(TALKDESK_DIR, "expected-config.yaml");
  const openapiFile = opt("--openapi");
  const json = flag("--json");
  if (flag("--emit-template")) {
    process.stdout.write(emitTemplate(expectedFile));
    return 0;
  }
  const observedFile = args[0];
  if (!observedFile) {
    console.error("usage: drift-check.mjs <observed.yaml> [--expected <file>] [--openapi <file>] [--json] | --emit-template");
    return 3;
  }
  let result;
  try {
    result = runDriftCheck({ observedFile, expectedFile, openapiFile });
  } catch (err) {
    console.error(`drift-check error: ${err.message}`);
    return 3;
  }
  if (json) console.log(JSON.stringify(result, null, 2));
  else printHuman(result);
  return result.verdict === "CLEAN" ? 0 : result.verdict === "DRIFT" ? 1 : 2;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv);
}
